/**
 * File: Generates exact, reviewable declaration locations for authored Rust, TypeScript, JavaScript, and Assembly.
 * Major symbols: sourceRoots, extractSymbols, renderIndex, and main generation/check path.
 * State: deterministic extension filters and declaration patterns; no network or external process state.
 */

import { readdir, readFile, writeFile } from "node:fs/promises";
import { relative, resolve } from "node:path";

const repositoryRoot = resolve(import.meta.dirname, "..");
const indexPath = resolve(repositoryRoot, "docs", "code-index.md");
const sourceRoots = ["src", "tests", "web/src", "web/tests", "web/scripts", "scripts", "examples"];
const includedExtensions = new Set([".rs", ".ts", ".mjs", ".asm"]);
const checkOnly = process.argv.includes("--check");

const files = [];
for (const root of sourceRoots) {
  await collectFiles(resolve(repositoryRoot, root), files);
}
files.sort((left, right) => left.localeCompare(right));
const rendered = await renderIndex(files);

if (checkOnly) {
  const current = await readFile(indexPath, "utf8");
  if (current !== rendered) {
    throw new Error("docs/code-index.md is stale; run `npm run code-index`");
  }
  console.log(`code index is current for ${files.length} authored files`);
} else {
  await writeFile(indexPath, rendered);
  console.log(`indexed ${files.length} authored files`);
}

async function collectFiles(directory, output) {
  const entries = await readdir(directory, { withFileTypes: true });
  for (const entry of entries) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) {
      await collectFiles(path, output);
    } else {
      const extension = entry.name.slice(entry.name.lastIndexOf("."));
      if (includedExtensions.has(extension)) {
        output.push(path);
      }
    }
  }
}

async function renderIndex(paths) {
  const output = [
    "# Code Index",
    "",
    "> Generated by `scripts/generate-code-index.mjs`. Do not edit declaration rows manually.",
    "",
    "This index supplies exact line locations while source-file headers stay readable and resilient to ordinary edits.",
    "",
  ];
  for (const path of paths) {
    const displayPath = relative(repositoryRoot, path).replaceAll("\\", "/");
    const text = await readFile(path, "utf8");
    const symbols = extractSymbols(displayPath, text);
    output.push(`## \`${displayPath}\``, "", "| Line | Kind | Declaration |", "|---:|---|---|");
    if (symbols.length === 0) {
      output.push("| — | file | No named declarations |", "");
    } else {
      for (const symbol of symbols) {
        output.push(`| ${symbol.line} | ${symbol.kind} | \`${escapeCell(symbol.name)}\` |`);
      }
      output.push("");
    }
  }
  return `${output.join("\n").trimEnd()}\n`;
}

function extractSymbols(path, text) {
  const patterns = path.endsWith(".rs")
    ? [
        ["type", /^\s*(?:pub(?:\([^)]*\))?\s+)?(?:struct|enum|trait|type)\s+([A-Za-z_][A-Za-z0-9_]*)/],
        ["function", /^\s*(?:pub(?:\([^)]*\))?\s+)?(?:const\s+)?fn\s+([A-Za-z_][A-Za-z0-9_]*)/],
        ["constant", /^\s*(?:pub(?:\([^)]*\))?\s+)?const\s+([A-Z][A-Z0-9_]*)/],
        ["implementation", /^\s*impl(?:<[^>]+>)?\s+([A-Za-z_][A-Za-z0-9_]*)/],
      ]
    : path.endsWith(".asm")
      ? [["label", /^\s*([A-Za-z_][A-Za-z0-9_]*):/]]
      : [
          ["type", /^\s*(?:export\s+)?(?:interface|type|class)\s+([A-Za-z_$][A-Za-z0-9_$]*)/],
          ["function", /^\s*(?:export\s+)?(?:async\s+)?function\s+([A-Za-z_$][A-Za-z0-9_$]*)/],
          ["state", /^\s*(?:export\s+)?(?:const|let)\s+([A-Za-z_$][A-Za-z0-9_$]*)/],
        ];
  const symbols = [];
  for (const [index, line] of text.split(/\r?\n/u).entries()) {
    for (const [kind, pattern] of patterns) {
      const match = pattern.exec(line);
      if (match?.[1] !== undefined) {
        symbols.push({ line: index + 1, kind, name: match[1] });
        break;
      }
    }
  }
  return symbols;
}

function escapeCell(value) {
  return value.replaceAll("|", "\\|").replaceAll("`", "\\`");
}

